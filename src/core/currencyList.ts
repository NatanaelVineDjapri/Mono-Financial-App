// Every foreign currency a Valas pocket can hold: the ones the Exchange Rate API (open.er-api.com) serves
// that are real, current ISO 4217 currencies. Left out on purpose: IRR (a rate of Rp0,01 cannot be
// held in rate_e4 without losing precision), CLF and XDR (units of account), CNH (offshore yuan, the same
// money as CNY), the retired SLL, ZWL and HRK, and the API's non-ISO territory codes (FOK, GGP, IMP, JEP,
// KID, TVD).
//
// `minorFactor` is ISO 4217's minor unit: 1 for no minor unit (yen, won, dong), 100 for cents, 1000 for
// three decimals (the Gulf and North African dinars, the Omani rial). It is what `currencies.minor_factor`
// holds (migration 4 -> 5 adds the rows; the first twelve have been there since schema v1). The order is
// the order of the Add-currency sheet: the twelve most used first, then the rest by code.
