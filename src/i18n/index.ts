// The one module the app imports its text from. Every sentence is a function that exists in both
// dictionaries, id.ts (Indonesian) and en.ts (English); the wrapper below picks the dictionary
// on EVERY call from the current language (src/i18n/lang.ts), so a screen that redraws after the
// language changed shows the new language. Generated from id.ts's exports and checked by
// src/i18n/__tests__/parity.test.ts: add a sentence to both files, then to this list.
import * as en from './en';
import * as id from './id';
import { getLanguage } from './lang';

function pick<F extends (...args: never[]) => unknown>(english: F, indonesian: F): F {
  return ((...args: Parameters<F>) => (getLanguage() === 'en' ? english : indonesian)(...args)) as F;
}

